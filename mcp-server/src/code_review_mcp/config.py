"""Configuration for the code-review MCP server.

Everything is overridable via environment variables so the same server
works against any LM Studio model without code changes.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field


# File extensions treated as reviewable source code.
DEFAULT_EXTENSIONS = {
    # Application code.
    ".py", ".js", ".jsx", ".ts", ".tsx", ".java", ".kt", ".kts",
    ".c", ".h", ".cpp", ".hpp", ".cc", ".cs", ".go", ".rs", ".rb",
    ".php", ".swift", ".scala", ".sh", ".ps1", ".sql", ".html",
    ".css", ".scss", ".vue", ".svelte", ".dart", ".lua", ".r", ".m",
    # Infrastructure and configuration. In a Kubernetes, Terraform or CI
    # repository this IS the code: privileged containers, permissive RBAC,
    # exposed services and hardcoded secrets all live in YAML, and leaving
    # these out reviews such a repository without reading the part that
    # deploys it.
    ".yaml", ".yml", ".json", ".toml", ".xml",
    ".tf", ".tfvars", ".hcl", ".gradle",
}

# Deliberately NOT reviewable, even though they are text and would parse:
# dotenv files exist to hold credentials, and sending one to a model would
# put live secrets in its context (and in the host's chat log) for no
# review value. Ask for them explicitly if you really mean to.
NEVER_DEFAULT_NAMES = {".env", ".env.local", ".env.production", ".npmrc",
                       ".pypirc", ".netrc", "id_rsa", "id_ed25519"}

# Reviewable files that have no extension to match on. A Dockerfile carries
# as much risk as any .py file — root users, baked-in secrets, unpinned
# base images — so it is matched by name instead.
FILENAME_LANGUAGES = {
    "dockerfile": "dockerfile",
    "containerfile": "dockerfile",
    "makefile": "make",
    "jenkinsfile": "groovy",
    "vagrantfile": "ruby",
    "procfile": "procfile",
}

# Directories never worth reviewing.
SKIP_DIRS = {
    ".git", ".hg", ".svn", "node_modules", "__pycache__", ".venv", "venv",
    "dist", "build", "target", ".idea", ".vscode", "vendor", ".tox",
    ".mypy_cache", ".pytest_cache", "coverage", ".next", ".nuxt",
}

EXTENSION_LANGUAGES = {
    ".py": "python", ".js": "javascript", ".jsx": "javascript",
    ".ts": "typescript", ".tsx": "typescript", ".java": "java",
    ".kt": "kotlin", ".kts": "kotlin", ".c": "c", ".h": "c",
    ".cpp": "cpp", ".hpp": "cpp", ".cc": "cpp", ".cs": "csharp",
    ".go": "go", ".rs": "rust", ".rb": "ruby", ".php": "php",
    ".swift": "swift", ".scala": "scala", ".sh": "shell",
    ".ps1": "powershell", ".sql": "sql", ".html": "html",
    ".css": "css", ".scss": "scss", ".vue": "vue",
    ".svelte": "svelte", ".dart": "dart", ".lua": "lua",
    ".r": "r", ".m": "objective-c",
    ".yaml": "yaml", ".yml": "yaml", ".json": "json", ".toml": "toml",
    ".xml": "xml", ".tf": "terraform", ".tfvars": "terraform",
    ".hcl": "hcl", ".gradle": "gradle",
}


# Markers that generated files put near the top of themselves. Matched
# case-insensitively against the head of the file only.
_GENERATED_MARKERS = (
    "@generated",
    "do not edit",
    "code generated by",
    "this file was automatically generated",
    "this file is generated",
    "autogenerated",
    "auto-generated",
    "generated by nbconvert",
    "# sourcemappingurl=",
)

# A human does not write a 5000-character line. Below that, minification is
# inferred from the line-length DISTRIBUTION instead, so a source file with
# one long string constant or a wide data table is not mistaken for one.
_HARD_LINE_LIMIT = 5000
_LONG_LINE = 1000
_MEAN_LINE = 200
# Below this, even a single-line file is cheap to review, so let it through:
# small one-liners are usually config, not a minified bundle.
_MIN_GENERATED_BYTES = 20_000


def looks_generated(name: str, content: str) -> str | None:
    """Reason this file looks machine-generated, or None if it reads human.

    Minified bundles and notebook exports cost enormous review time and
    yield nothing: the model cannot say anything useful about
    `var a=1;var b=2;...` repeated for half a megabyte. Worse, a minified
    file is ONE line, so the chunker cannot split it and the whole thing
    goes to the model in a single request.

    The test is what the content looks like, not what it is called, so it
    catches the next bundle nobody thought to blacklist. Deliberately
    conservative: skipping a file a human wrote is worse than reviewing a
    generated one, so both size and shape must agree.
    """
    head = content[:4000].lower()
    for marker in _GENERATED_MARKERS:
        if marker in head:
            return f"generated file (contains {marker!r})"

    if len(content) < _MIN_GENERATED_BYTES:
        return None

    lines = content.splitlines() or [content]
    longest = max((len(line) for line in lines), default=0)
    mean = len(content) / len(lines)
    if longest >= _HARD_LINE_LIMIT:
        return (f"minified or generated (longest line {longest:,} chars; "
                "no human writes that)")
    if longest >= _LONG_LINE and mean >= _MEAN_LINE:
        return (f"minified or generated (mean line {mean:.0f} chars, "
                f"longest {longest:,})")
    return None


def classify_file(name: str, extensions: set[str],
                  match_by_name: bool = True) -> str | None:
    """Return the language of a reviewable file, or None to exclude it.

    Extension first, then the well-known extensionless names — including
    the Dockerfile.prod / prod.Dockerfile spellings.

    match_by_name is False when the caller supplied its own extension
    list: an explicit filter should return exactly what was asked for, not
    quietly add files it never mentioned.
    """
    lower = name.lower()
    if lower in NEVER_DEFAULT_NAMES:
        return None
    _, _, tail = lower.rpartition(".")
    ext = f".{tail}" if tail and tail != lower else ""
    if ext in extensions:
        return EXTENSION_LANGUAGES.get(ext, "unknown")
    if match_by_name:
        for stem, language in FILENAME_LANGUAGES.items():
            if (lower == stem or lower.startswith(f"{stem}.")
                    or lower.endswith(f".{stem}")):
                return language
    return None


def _optional_float(raw: str) -> float | None:
    """A float setting where empty or "none" means "do not send it"."""
    raw = raw.strip()
    return None if raw.lower() in ("", "none") else float(raw)


@dataclass
class Settings:
    """Runtime settings, sourced from environment variables."""

    # LM Studio's OpenAI-compatible endpoint.
    lm_base_url: str = field(
        default_factory=lambda: os.getenv("LMSTUDIO_BASE_URL", "http://localhost:1234/v1")
    )
    # Model identifier as shown in LM Studio's server page. Empty string lets
    # LM Studio route to whichever model is currently loaded.
    lm_model: str = field(default_factory=lambda: os.getenv("LMSTUDIO_MODEL", ""))
    # LM Studio ignores the key but the OpenAI client requires one.
    lm_api_key: str = field(default_factory=lambda: os.getenv("LMSTUDIO_API_KEY", "lm-studio"))

    # Per-request character budget for file content. Files larger than this
    # are split into multiple chunks. ~48k chars is roughly 12-16k tokens,
    # which fits comfortably in Gemma's context alongside the prompts.
    max_chunk_chars: int = field(
        default_factory=lambda: int(os.getenv("REVIEW_MAX_CHUNK_CHARS", "48000"))
    )
    # Files above this size (bytes) are skipped entirely (likely generated).
    max_file_bytes: int = field(
        default_factory=lambda: int(os.getenv("REVIEW_MAX_FILE_BYTES", "512000"))
    )
    # Cap on the number of files reviewed in one run (safety valve).
    max_files: int = field(default_factory=lambda: int(os.getenv("REVIEW_MAX_FILES", "500")))
    # Skip minified bundles and notebook exports (see looks_generated).
    # REVIEW_SKIP_GENERATED=0 reviews them anyway, at real cost.
    skip_generated: bool = field(
        default_factory=lambda: os.getenv("REVIEW_SKIP_GENERATED", "1") != "0"
    )
    # Run the deterministic scanner tier (Semgrep/Gitleaks/Trivy, packaged
    # separately as `repo_scanner`) over the clone before reviewing, and feed
    # its findings to the model. No-ops when that package is not installed,
    # so this component still runs standalone. REVIEW_RUN_SCANNER=0 disables.
    run_scanner: bool = field(
        default_factory=lambda: os.getenv("REVIEW_RUN_SCANNER", "1") != "0"
    )
    # Sampling temperature; low = deterministic, focused reviews. Empty or
    # "none" leaves it out of the request, for models that refuse one.
    temperature: float | None = field(default_factory=lambda: _optional_float(
        os.getenv("REVIEW_TEMPERATURE", "0.2")))
    # Max tokens for each review response (deep mode).
    max_tokens: int = field(default_factory=lambda: int(os.getenv("REVIEW_MAX_TOKENS", "4096")))
    # Token CAP for the single brief-mode response. Generous because hidden
    # reasoning tokens count against it too; the schema keeps the actual
    # answer short, so this is headroom, not a target.
    brief_max_tokens: int = field(
        default_factory=lambda: int(os.getenv("REVIEW_BRIEF_MAX_TOKENS", "3000"))
    )
    # Brief mode covers the WHOLE repo in digest batches: per-batch char
    # budget and the per-file cap (only the head of each file is included).
    # Batches = ceil(total_capped_chars / budget); each batch is one LLM call.
    brief_pack_chars: int = field(
        default_factory=lambda: int(os.getenv("REVIEW_BRIEF_PACK_CHARS", "12000"))
    )
    brief_file_cap: int = field(
        default_factory=lambda: int(os.getenv("REVIEW_BRIEF_FILE_CAP", "1200"))
    )
    # Files with fewer non-whitespace chars than this are marked trivial and
    # never sent to the LLM at all (empty __init__.py and friends).
    trivial_file_chars: int = field(
        default_factory=lambda: int(os.getenv("REVIEW_TRIVIAL_FILE_CHARS", "50"))
    )
    # Retries per chunk when the model returns unparseable JSON.
    json_retries: int = field(default_factory=lambda: int(os.getenv("REVIEW_JSON_RETRIES", "2")))
    # Liveness watchdog: the model may generate for as long as it needs, but
    # if NO tokens arrive for this many seconds the stream is declared dead.
    # Generous default: prompt prefill on large files and JIT model loading
    # both produce zero tokens and must not look like a stall.
    stall_timeout: float = field(
        default_factory=lambda: float(os.getenv("REVIEW_STALL_TIMEOUT", "300"))
    )
    # Minimum seconds between heartbeat progress updates while streaming.
    heartbeat_interval: float = field(
        default_factory=lambda: float(os.getenv("REVIEW_HEARTBEAT_SECONDS", "3"))
    )
    # Concurrent LLM requests for brief batches and deep per-file reviews.
    # DEFAULT 1 (serial): local single-model servers gain nothing from
    # concurrency unless parallel request processing is explicitly enabled,
    # and some choke on it. Raise only after enabling parallelism in the
    # LLM server (LM Studio: parallel request processing).
    parallel: int = field(
        default_factory=lambda: max(1, min(8, int(os.getenv("REVIEW_PARALLEL", "1"))))
    )
    # Relative output paths are resolved against this directory. In the Docker
    # image it defaults to /reports so reports land in the mounted volume.
    output_dir: str = field(default_factory=lambda: os.getenv("REVIEW_OUTPUT_DIR", ""))

    # Personal access token used to clone PRIVATE repositories over HTTPS.
    # Read from the ENVIRONMENT ONLY and never accepted as a tool argument:
    # an argument would travel through the MCP protocol into the chat model's
    # context and the host's logs. The token is handed to git through
    # GIT_ASKPASS (see repo_ingest), so it never appears in a command line,
    # a clone URL, the report, or a log file [threat model: "clone token
    # appears in logs or process list" -> URL redaction, no argument token].
    github_token: str = field(
        default_factory=lambda: (
            os.getenv("GITHUB_TOKEN") or os.getenv("GH_TOKEN") or ""
        ).strip()
    )


settings = Settings()
