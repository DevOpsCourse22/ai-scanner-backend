"""Mock LM Studio: an OpenAI-compatible server for testing without a real LLM.

Stdlib only — no dependencies. Serves /v1/models and /v1/chat/completions
(streaming and non-streaming) and always answers with a valid review JSON,
so the whole MCP pipeline can be exercised while LM Studio is down.

Usage:
    python tests/mock_llm_server.py                    # instant responses
    python tests/mock_llm_server.py --delay 0.5        # slow generation
    python tests/mock_llm_server.py --stall-after 5    # wedge mid-stream
    python tests/mock_llm_server.py --port 9999

--delay N       seconds between streamed chunks (simulates a slow model;
                the review takes long but tokens keep flowing = healthy).
--stall-after N stop sending after N chunks and hang (simulates a wedged
                model; the client's stall watchdog must fire).
"""

from __future__ import annotations

import argparse
import json
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

MODEL_ID = "mock/gemma-4-test"
# Extra ids reported by /v1/models. A real server offers several, and the
# console's model picker is built from this list, so --models lets that be
# exercised without a GPU.
EXTRA_MODELS: list[str] = []

DELAY = 0.0
STALL_AFTER = 0  # 0 = never stall


def build_review(file_path: str) -> dict:
    return {
        "file": file_path,
        "summary": f"Mock review of {file_path}: structure is reasonable, "
                   "one simulated issue found for pipeline testing.",
        "issues": [
            {
                "severity": "medium",
                "line": 1,
                "title": "Simulated issue",
                "description": "This finding is generated by the mock LLM server.",
                "suggestion": "No action needed; this validates the pipeline.",
            }
        ],
        "positives": ["Pipeline reached the model and parsed pure JSON."],
        "score": 7,
    }


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, fmt, *args):  # quieter logs
        print(f"[mock-llm] {fmt % args}")

    def do_GET(self):
        if self.path == "/v1/models":
            body = json.dumps({
                "object": "list",
                "data": [{"id": m, "object": "model", "owned_by": "mock"}
                         for m in [MODEL_ID, *EXTRA_MODELS]],
            }).encode()
            self._respond(200, "application/json", body)
        else:
            self._respond(404, "text/plain", b"not found")

    def do_POST(self):
        if self.path != "/v1/chat/completions":
            self._respond(404, "text/plain", b"not found")
            return
        length = int(self.headers.get("Content-Length", 0))
        request = json.loads(self.rfile.read(length) or b"{}")

        # Echo back the file path found in the user message, if any.
        file_path = "unknown"
        for message in request.get("messages", []):
            if message.get("role") == "user":
                try:
                    file_path = json.loads(message["content"]).get("file", "unknown")
                except (json.JSONDecodeError, TypeError):
                    file_path = "ping"
        answer = json.dumps(build_review(file_path)) if file_path != "ping" \
            else '{"pong": true}'

        if request.get("stream"):
            self._stream_response(answer)
        else:
            body = json.dumps({
                "id": "mock-1", "object": "chat.completion", "model": MODEL_ID,
                "choices": [{"index": 0, "finish_reason": "stop",
                             "message": {"role": "assistant", "content": answer}}],
            }).encode()
            self._respond(200, "application/json", body)

    def _stream_response(self, answer: str) -> None:
        self.send_response(200)
        self.send_header("Content-Type", "text/event-stream")
        self.send_header("Cache-Control", "no-cache")
        self.send_header("Connection", "close")
        self.end_headers()

        # Split the answer into small chunks like a real token stream.
        size = 12
        pieces = [answer[i:i + size] for i in range(0, len(answer), size)]
        for count, piece in enumerate(pieces, start=1):
            if STALL_AFTER and count > STALL_AFTER:
                print(f"[mock-llm] STALLING after {STALL_AFTER} chunks (simulated wedge)")
                time.sleep(3600)  # wedge: client watchdog must fire
            event = {
                "id": "mock-1", "object": "chat.completion.chunk", "model": MODEL_ID,
                "choices": [{"index": 0, "finish_reason": None,
                             "delta": {"content": piece}}],
            }
            self.wfile.write(f"data: {json.dumps(event)}\n\n".encode())
            self.wfile.flush()
            if DELAY:
                time.sleep(DELAY)
        done = {
            "id": "mock-1", "object": "chat.completion.chunk", "model": MODEL_ID,
            "choices": [{"index": 0, "finish_reason": "stop", "delta": {}}],
        }
        self.wfile.write(f"data: {json.dumps(done)}\n\ndata: [DONE]\n\n".encode())
        self.wfile.flush()

    def _respond(self, code: int, ctype: str, body: bytes) -> None:
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)


def main() -> None:
    global DELAY, STALL_AFTER, EXTRA_MODELS
    parser = argparse.ArgumentParser(description="Mock LM Studio server")
    parser.add_argument("--port", type=int, default=1234)
    parser.add_argument("--delay", type=float, default=0.0)
    parser.add_argument("--stall-after", type=int, default=0)
    parser.add_argument("--models", default="",
                        help="Extra comma-separated model ids to advertise, "
                             "for exercising the console's model picker.")
    args = parser.parse_args()
    DELAY, STALL_AFTER = args.delay, args.stall_after
    EXTRA_MODELS = [m.strip() for m in args.models.split(",") if m.strip()]

    server = ThreadingHTTPServer(("0.0.0.0", args.port), Handler)
    print(f"[mock-llm] listening on 0.0.0.0:{args.port} "
          f"(delay={DELAY}s, stall_after={STALL_AFTER or 'never'})")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    main()
